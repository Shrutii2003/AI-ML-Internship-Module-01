# Python Loops Practice

# For loop
print("For Loop:")

for i in range(1, 6):
    print(i)

# While loop
print("\nWhile Loop:")

count = 1

while count <= 5:
    print(count)
    count += 1

# Loop through a list
print("\nNames:")

names = ["Shruti", "Niket", "Priyanka"]

for name in names:
    print(name)
